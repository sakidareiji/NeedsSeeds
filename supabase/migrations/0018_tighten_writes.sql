--   1. notifications … ユーザーは「既読にする」以外を書き換えられないようにする
--   2. solutions.url  … リダイレクト先を http(s) に限定する
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. 通知は read_at だけ更新できれば足りる
--
-- 現状は行の所有(auth.uid() = user_id)しか見ておらず、テーブル全体の UPDATE 権限が
-- 残っているため、自分宛の通知の type や payload を REST から書き換えられる。
-- 表示が壊れる程度の実害だが、列を絞れば済むので絞る。
-- ---------------------------------------------------------------------------
revoke update on public.notifications from anon, authenticated;
grant update (read_at) on public.notifications to authenticated;


-- ---------------------------------------------------------------------------
-- 2. 解決策のURLは http(s) のみ
--
-- /go/[id] は post_solutions から引いた URL へ無検証でリダイレクトしている。
-- 登録するのは運営だけなので実害は薄いが、javascript: や data: が入り込むと
-- クリック計測を経由した誘導に使えてしまうため、DB 側で形式を保証する
-- (アプリ側でもリダイレクト直前に検証する)。
-- ---------------------------------------------------------------------------
alter table public.solutions
  add constraint solutions_url_scheme_check
  check (url ~* '^https?://');
